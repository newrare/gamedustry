#!/usr/bin/env node
/*
  gen-catalogues — write both game catalogues from the manifests.

    node tools/build/gen-catalogues.mjs
    node tools/build/gen-catalogues.mjs --check   # fail if either is stale

  A game is described once, in games/<slug>/manifest.json. Two places show that
  description and both are generated from it:

    site/games.js   the public site: name, accent, draft, one tagline and three
                    tags per language
    index.html      the developer gallery: name, icon, the long English
                    write-up, tags, accent — inside the marked GAMES block

  Order follows each manifest's `order` field (a curated sequence, in steps of ten
  so a game can be slipped between two others); manifests without one fall to the
  end, alphabetically.
*/

import { readFile, writeFile } from 'node:fs/promises';
import { readdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const CHECK = process.argv.includes('--check');

const GEN_OPEN = '  // >>> GENERATED by tools/build/gen-catalogues.mjs — edit the manifests, not this.';
const GEN_CLOSE = '  // <<< GENERATED';

async function manifests() {
  const dirs = readdirSync(path.join(ROOT, 'games'), { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .filter((slug) => existsSync(path.join(ROOT, 'games', slug, 'manifest.json')))
    .sort();

  const out = [];
  for (const slug of dirs) {
    const raw = await readFile(path.join(ROOT, 'games', slug, 'manifest.json'), 'utf8');
    const m = JSON.parse(raw);
    if (m.slug !== slug) throw new Error(`games/${slug}/manifest.json: slug says "${m.slug}"`);
    for (const field of ['title', 'theme', 'copy']) {
      if (!m[field]) throw new Error(`games/${slug}/manifest.json: missing "${field}"`);
    }
    out.push(m);
  }
  // Curated order, with unordered manifests trailing alphabetically.
  return out.sort((a, b) => {
    const oa = typeof a.order === 'number' ? a.order : Infinity;
    const ob = typeof b.order === 'number' ? b.order : Infinity;
    return oa - ob || a.slug.localeCompare(b.slug);
  });
}

// ── site/games.js ──────────────────────────────────────────────────────────
function siteCatalogue(list) {
  const entries = list.map((m) => {
    const draft = m.draft ? '\n    draft: true,' : '';
    const tags = (lang) => m.copy[lang].tags.map((t) => JSON.stringify(t)).join(', ');
    return `  {
    slug: ${JSON.stringify(m.slug)},
    name: ${JSON.stringify(m.title)},
    accent: [${JSON.stringify(m.theme.accent)}, ${JSON.stringify(m.theme.accent2)}],${draft}
    fr: {
      tagline: ${JSON.stringify(m.copy.fr.tagline)},
      tags: [${tags('fr')}]
    },
    en: {
      tagline: ${JSON.stringify(m.copy.en.tagline)},
      tags: [${tags('en')}]
    }
  }`;
  });

  return `/*
  Playable catalogue rendered by the Playables section.

  GENERATED by tools/build/gen-catalogues.mjs from games/<slug>/manifest.json.
  Do not edit: change the manifest and run the generator.

  The site builder rewrites this array again on the way to dist/site/, adding for
  each game:
    icon    - true when assets/icon/thumb/<slug>.png exists
    screens - how many assets/screen/<slug>-NN.jpg were found

  Two ways a game stays off the public site:
    draft: true   - still in construction, set in the manifest
    no icon       - dropped and reported, because a card with no artwork is a
                    broken card, not a discreet one
*/
window.GAMES = [
${entries.join(',\n')}
];
`;
}

// ── the GAMES block inside the root index.html ─────────────────────────────
function galleryBlock(list) {
  const lines = list.map((m) => {
    const tags = m.copy.en.tags.map((t) => JSON.stringify(t)).join(',');
    const desc = JSON.stringify(m.description || m.copy.en.tagline);
    return `  { slug:${JSON.stringify(m.slug)}, name:${JSON.stringify(m.title)}, icon:${JSON.stringify(m.slug)},
    desc:${desc},
    tags:[${tags}], accent:[${JSON.stringify(m.theme.accent)},${JSON.stringify(m.theme.accent2)}] }`;
  });
  return `${GEN_OPEN}\nvar GAMES = [\n${lines.join(',\n')}\n];\n${GEN_CLOSE}`;
}

function replaceGalleryBlock(html, block) {
  const open = html.indexOf(GEN_OPEN);
  if (open >= 0) {
    const close = html.indexOf(GEN_CLOSE, open);
    if (close < 0) throw new Error('index.html: generated block opened but never closed');
    return html.slice(0, open) + block + html.slice(close + GEN_CLOSE.length);
  }
  // First run: adopt the hand-written array.
  const a = html.indexOf('var GAMES = [');
  if (a < 0) throw new Error('index.html: no GAMES array and no generated block');
  const b = html.indexOf('\n];', a);
  if (b < 0) throw new Error('index.html: GAMES array is not terminated');
  return html.slice(0, a) + block + html.slice(b + '\n];'.length);
}

async function main() {
  const list = await manifests();

  const targets = [
    { file: 'site/games.js', text: siteCatalogue(list) },
    { file: 'index.html', text: null }  // patched in place, below
  ];

  const rootPath = path.join(ROOT, 'index.html');
  const rootHtml = await readFile(rootPath, 'utf8');
  targets[1].text = replaceGalleryBlock(rootHtml, galleryBlock(list));

  let stale = 0;
  for (const t of targets) {
    const full = path.join(ROOT, t.file);
    const current = existsSync(full) ? await readFile(full, 'utf8') : null;
    if (current === t.text) {
      console.log(`OK    ${t.file}`);
      continue;
    }
    if (CHECK) { stale++; console.log(`STALE ${t.file}`); continue; }
    await writeFile(full, t.text);
    console.log(`wrote ${t.file}`);
  }

  const drafts = list.filter((m) => m.draft).map((m) => m.slug);
  console.log(`${list.length} manifests${drafts.length ? `, drafts: ${drafts.join(' ')}` : ''}`);

  if (CHECK && stale) {
    console.log(`\n${stale} catalogue(s) are stale — run the generator.`);
    process.exit(1);
  }
}

main().catch((err) => { console.error('gen-catalogues failed:', err.message); process.exit(1); });
